// Replace {token} with vars.token; unknown tokens stay as written, which is
// also what protects {{user}}/{{char}} (their inner braces never match a
// provided var).
export function fill(template, vars) {
    return String(template ?? '').replace(/\{(\w+)\}/g, (m, k) => (vars && k in vars) ? String(vars[k]) : m);
}
